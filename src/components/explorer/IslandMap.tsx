import {
  forwardRef,
  useEffect,
  useImperativeHandle,
  useLayoutEffect,
  useMemo,
  useRef,
  useState,
  type MouseEvent,
  type PointerEvent,
} from "react";
import { geoMercator, geoPath, type GeoPath, type GeoPermissibleObjects } from "d3-geo";
import { select } from "d3-selection";
import { zoom, zoomIdentity, type ZoomBehavior, type ZoomTransform } from "d3-zoom";
import { municipioById, type Municipio } from "@/data/pr/places";
import type { PrMetric } from "@/data/pr/metrics";
import { colorForValue } from "@/data/scale";
import { MISSING_COPY, missingReason } from "@/data/pr/missing";
// Generated by scripts/geo from the official TIGER/Line 2024 extract (data/raw/geo).
import geometry from "../../../data/generated/municipios.geometry.json";

export type IslandMapHandle = {
  focus: (key: string) => void;
  reset: () => void;
  zoomBy: (factor: number) => void;
};

type Props = {
  metric: PrMetric;
  min: number;
  max: number;
  selectedId: string | null;
  places?: Municipio[];
  flat?: boolean;
  flatValue?: number | null;
  onSelect: (id: string | null) => void;
};

type Shape = { id: string; name: string; d: string; feature: GeoPermissibleObjects };

const collection = geometry as unknown as GeoJSON.FeatureCollection;

export const IslandMap = forwardRef<IslandMapHandle, Props>(function IslandMap(
  { metric, min, max, selectedId, places, flat = false, flatValue = null, onSelect },
  ref,
) {
  const containerRef = useRef<HTMLDivElement>(null);
  const svgRef = useRef<SVGSVGElement>(null);
  const groupRef = useRef<SVGGElement>(null);
  const zoomRef = useRef<ZoomBehavior<SVGSVGElement, unknown> | null>(null);
  const transformRef = useRef<ZoomTransform>(zoomIdentity);
  const frameRef = useRef(0);
  const pathRef = useRef<GeoPath | null>(null);
  const shapesRef = useRef<Shape[]>([]);
  const sizeRef = useRef({ width: 0, height: 0 });
  const draggedRef = useRef(false);
  const originRef = useRef<{ x: number; y: number } | null>(null);
  const pointerRef = useRef<{ x: number; y: number } | null>(null);
  const tipRef = useRef<HTMLDivElement>(null);
  const [size, setSize] = useState({ width: 0, height: 0 });
  const [hoveredKey, setHoveredKey] = useState<string | null>(null);
  const byId = useMemo(
    () => (places ? new Map(places.map((place) => [place.id, place])) : municipioById),
    [places],
  );

  const projected = useMemo(() => {
    if (size.width < 20 || size.height < 20) return null;
    const projection = geoMercator().fitExtent(
      [
        [20, 28],
        [size.width - 20, size.height - 28],
      ],
      collection,
    );
    const path = geoPath(projection);
    const shapes = collection.features
      .map((feature) => {
        const props = feature.properties as { id: string; name: string };
        return {
          id: props.id,
          name: props.name,
          d: path(feature as GeoPermissibleObjects) ?? "",
          feature: feature as GeoPermissibleObjects,
        };
      })
      .filter((shape) => shape.d);
    return { shapes, path };
  }, [size.height, size.width]);

  pathRef.current = projected?.path ?? null;
  shapesRef.current = projected?.shapes ?? [];
  sizeRef.current = size;

  useEffect(() => {
    const element = containerRef.current;
    if (!element) return;
    const measure = () => {
      const rect = element.getBoundingClientRect();
      const width = Math.round(rect.width);
      const height = Math.round(rect.height);
      setSize((current) =>
        current.width === width && current.height === height ? current : { width, height },
      );
    };
    measure();
    const observer = new ResizeObserver(measure);
    observer.observe(element);
    return () => observer.disconnect();
  }, []);

  useEffect(() => {
    const svg = svgRef.current;
    if (!svg || size.width < 20 || size.height < 20) return;
    const behavior = zoom<SVGSVGElement, unknown>()
      .scaleExtent([1, 12])
      .extent([
        [0, 0],
        [size.width, size.height],
      ])
      .translateExtent([
        [-size.width * 0.35, -size.height * 0.35],
        [size.width * 1.35, size.height * 1.35],
      ])
      .on("zoom", (event) => {
        groupRef.current?.setAttribute("transform", event.transform.toString());
        transformRef.current = event.transform;
        if (event.sourceEvent) cancelAnimationFrame(frameRef.current);
      });
    zoomRef.current = behavior;
    const selection = select(svg);
    selection.call(behavior);
    selection.on("dblclick.zoom", null);
    selection.call(behavior.transform, zoomIdentity);
    return () => {
      selection.on(".zoom", null);
      cancelAnimationFrame(frameRef.current);
    };
  }, [size.height, size.width]);

  function flyTo(target: ZoomTransform) {
    const behavior = zoomRef.current;
    const svg = svgRef.current;
    if (!behavior || !svg) return;
    const reduce = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
    if (reduce) {
      select(svg).call(behavior.transform, target);
      return;
    }
    const from = transformRef.current;
    const start = performance.now();
    cancelAnimationFrame(frameRef.current);
    const tick = (now: number) => {
      const t = Math.min(1, (now - start) / 520);
      const eased = 1 - (1 - t) ** 3;
      const next = zoomIdentity
        .translate(from.x + (target.x - from.x) * eased, from.y + (target.y - from.y) * eased)
        .scale(from.k + (target.k - from.k) * eased);
      select(svg).call(behavior.transform, next);
      if (t < 1) frameRef.current = requestAnimationFrame(tick);
    };
    frameRef.current = requestAnimationFrame(tick);
  }

  useImperativeHandle(ref, () => ({
    focus(key: string) {
      const hit = shapesRef.current.find((shape) => shape.id === key);
      const path = pathRef.current;
      const { width, height } = sizeRef.current;
      if (!hit || !path || width < 20) return;
      const [[x0, y0], [x1, y1]] = path.bounds(hit.feature);
      const dx = Math.max(x1 - x0, 8);
      const dy = Math.max(y1 - y0, 8);
      const k = Math.max(1.2, Math.min(10, 0.46 / Math.max(dx / width, dy / height)));
      flyTo(
        zoomIdentity
          .translate(width / 2 - k * ((x0 + x1) / 2), height / 2 - k * ((y0 + y1) / 2))
          .scale(k),
      );
    },
    reset() {
      flyTo(zoomIdentity);
    },
    zoomBy(factor: number) {
      const { width, height } = sizeRef.current;
      const current = transformRef.current;
      const nextK = Math.max(1, Math.min(12, current.k * factor));
      const worldX = (width / 2 - current.x) / current.k;
      const worldY = (height / 2 - current.y) / current.k;
      flyTo(zoomIdentity.translate(width / 2 - nextK * worldX, height / 2 - nextK * worldY).scale(nextK));
    },
  }));

  function placeTooltip(x: number, y: number) {
    const tip = tipRef.current;
    if (!tip) return;
    const pad = 14;
    let left = x + pad;
    let top = y + pad;
    if (left + tip.offsetWidth > window.innerWidth - 8) left = x - tip.offsetWidth - pad;
    if (top + tip.offsetHeight > window.innerHeight - 8) top = y - tip.offsetHeight - pad;
    tip.style.transform = `translate(${Math.max(8, left)}px, ${Math.max(8, top)}px)`;
  }

  useLayoutEffect(() => {
    if (!hoveredKey || !pointerRef.current) return;
    placeTooltip(pointerRef.current.x, pointerRef.current.y);
  }, [hoveredKey, metric.id]);

  const hovered = hoveredKey ? byId.get(hoveredKey) : undefined;
  const hoveredValue = flatValue != null ? flatValue : hovered ? hovered.values[metric.id] : null;

  function onPointerDown(event: PointerEvent<SVGSVGElement>) {
    draggedRef.current = false;
    originRef.current = { x: event.clientX, y: event.clientY };
  }

  function onPointerMove(event: PointerEvent<SVGSVGElement>) {
    const origin = originRef.current;
    if (origin) {
      const dx = event.clientX - origin.x;
      const dy = event.clientY - origin.y;
      if (dx * dx + dy * dy > 16) draggedRef.current = true;
    }
    pointerRef.current = { x: event.clientX, y: event.clientY };
    if (event.pointerType === "touch" || draggedRef.current) return;
    const key = (event.target as Element).getAttribute?.("data-key");
    if (key !== hoveredKey) setHoveredKey(key);
    if (key) placeTooltip(event.clientX, event.clientY);
  }

  function onClick(event: MouseEvent<SVGSVGElement>) {
    if (draggedRef.current) {
      draggedRef.current = false;
      return;
    }
    onSelect((event.target as Element).getAttribute?.("data-key"));
  }

  const selected = selectedId ? projected?.shapes.find((shape) => shape.id === selectedId) : undefined;
  const hoverDraw =
    hoveredKey && hoveredKey !== selectedId
      ? projected?.shapes.find((shape) => shape.id === hoveredKey)
      : undefined;

  return (
    <div ref={containerRef} className="relative h-full w-full overflow-hidden">
      {projected && (
        <svg
          ref={svgRef}
          className="map-svg h-full w-full touch-none"
          aria-label={`Mapa de Puerto Rico según ${metric.label}`}
          onPointerDown={onPointerDown}
          onPointerMove={onPointerMove}
          onPointerUp={() => {
            originRef.current = null;
          }}
          onPointerLeave={() => setHoveredKey(null)}
          onClick={onClick}
        >
          <g ref={groupRef}>
            {projected.shapes.map((shape) => {
              const place = byId.get(shape.id);
              const value = place ? place.values[metric.id] : null;
              const fill = flat ? "var(--color-accent)" : colorForValue(value, min, max, metric.scale);
              return (
                <path
                  key={shape.id}
                  data-key={shape.id}
                  d={shape.d}
                  className="map-municipio"
                  style={{ fill }}
                >
                  <title>{shape.name}</title>
                </path>
              );
            })}
            {hoverDraw && <path d={hoverDraw.d} className="map-outline map-outline-hover" />}
            {selected && <path d={selected.d} className="map-outline" />}
          </g>
        </svg>
      )}
      <div
        ref={tipRef}
        role="tooltip"
        className={
          hovered
            ? "pointer-events-none fixed top-0 left-0 z-30 max-w-56 rounded-md border border-border bg-surface px-3 py-2 shadow-float"
            : "pointer-events-none fixed top-0 left-0 z-30 hidden"
        }
      >
        {hovered && (
          <>
            <p className="font-display text-lg leading-tight">{hovered.name}</p>
            <p className="mt-1 text-xs tracking-wide text-muted uppercase">{metric.label}</p>
            <p className="mt-0.5 font-display text-2xl leading-none tabular-nums">
              {hoveredValue == null ? MISSING_COPY[missingReason(metric.id, hovered.id)].short : metric.format(hoveredValue)}
            </p>
          </>
        )}
      </div>
    </div>
  );
});
